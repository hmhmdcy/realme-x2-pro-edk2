#!/usr/bin/env python3
"""Map locally-rebuilt 9999x packages to their official repository version.

The delivery image contains packages whose version starts with 9999x.  That
is postmarketOS' way of marking a locally rebuilt package so it always sorts
above the upstream one, which also means apk never sees the official version
as an upgrade.  Those packages exist in no repository either, so a
full-system `apk upgrade` cannot resolve them.

This tool reads an APKINDEX.tar.gz (Alpine and postmarketOS use the same
format), reads the image's installed database, and prints the exact
name=version pairs that would replace each private build with the official
one.  It is offline only: it never contacts a device and never writes to a
root.
"""
from pathlib import Path
import argparse
import json
import re
import sys
import tarfile

p = argparse.ArgumentParser(description=__doc__)
p.add_argument("--index", type=Path, action="append", required=True,
               help="APKINDEX.tar.gz; repeat for more repositories")
p.add_argument("--db", type=Path, required=True,
               help="installed database extracted from the image")
p.add_argument("--json", type=Path)
p.add_argument("--shell", type=Path)
args = p.parse_args()


def index_versions(paths):
    """First version seen for each package name, in repository order."""
    versions = {}
    for path in paths:
        with tarfile.open(path, "r:gz") as archive:
            try:
                member = archive.extractfile("APKINDEX")
            except KeyError:
                continue
            if member is None:
                continue
            text = member.read().decode("utf-8", "replace")
        name = version = None
        for line in text.splitlines():
            if line.startswith("P:"):
                name = line[2:]
            elif line.startswith("V:") and name:
                version = line[2:]
            elif not line:
                if name and version and name not in versions:
                    versions[name] = version
                name = version = None
        if name and version and name not in versions:
            versions[name] = version
    return versions


def installed(path):
    rows = []
    name = version = None
    for line in path.read_text(errors="replace").splitlines():
        if line.startswith("P:"):
            name = line[2:]
        elif line.startswith("V:") and name:
            version = line[2:]
        elif not line:
            if name and version:
                rows.append((name, version))
            name = version = None
    if name and version:
        rows.append((name, version))
    return rows


official = index_versions(args.index)
private = [(n, v) for n, v in installed(args.db) if re.match(r"9999", v)]

mapped = []
unmapped = []
for name, version in sorted(private):
    want = official.get(name)
    if not want:
        unmapped.append((name, version))
        continue
    # postmarketOS prefixes a rebuilt package with exactly "9999", so
    # 99991.16.2-r1 is a rebuild of 1.16.2-r1 and 999923.13.9-r0 is a
    # rebuild of 23.13.9-r0.  Stripping more than four characters would eat
    # the leading digit of the upstream version.
    upstream = re.sub(r"^9999", "", version)
    mapped.append({
        "name": name,
        "installed": version,
        "official": want,
        "same_upstream": (upstream == want
                          or upstream.split("-r")[0] == want.split("-r")[0]),
    })

print("private builds: %d" % len(private))
print("found in index: %d" % len(mapped))
print("not in index:   %d" % len(unmapped))
print()
for item in mapped:
    mark = "same" if item["same_upstream"] else "diff"
    print("  %s  %-32s %-18s -> %s"
          % (mark, item["name"], item["installed"], item["official"]))
if unmapped:
    print()
    print("not in any supplied index (board or orphan packages stay as-is):")
    for name, version in unmapped:
        print("       %-32s %s" % (name, version))

if args.json:
    args.json.write_text(json.dumps({
        "schema": "samurai-official-version-map-v1",
        "indexes": [str(p) for p in args.index],
        "private": len(private),
        "mapped": mapped,
        "unmapped": [{"name": n, "installed": v} for n, v in unmapped],
    }, indent=2) + "\n")

if args.shell:
    lines = [
        "#!/bin/sh",
        "# Reinstall the official build of every locally rebuilt 9999x package.",
        "# Generated by linux-port/scripts/official-version-map.py; review first.",
        "set -eu",
        "apk add \\",
    ]
    for item in mapped:
        lines.append("\t'%s=%s' \\" % (item["name"], item["official"]))
    lines.append("\t")
    args.shell.write_text("\n".join(lines) + "\n")

sys.exit(0 if mapped else 1)

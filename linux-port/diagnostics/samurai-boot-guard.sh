#!/bin/sh
# SPDX-License-Identifier: BSD-3-Clause
#
# One-shot boot confirmation guard for a remotely unattended boot/logdump
# experiment.  It never runs unless an "armed" marker exists.  The next boot
# must create /run/samurai-boot-guard/confirmed within the configured window;
# otherwise the verified rollback boot/logdump pair is restored and the
# device reboots.

set -eu

state_dir=${SAMURAI_BOOT_GUARD_STATE_DIR:-/var/lib/samurai-boot-guard}
run_dir=${SAMURAI_BOOT_GUARD_RUN_DIR:-/run/samurai-boot-guard}
log_file=${SAMURAI_BOOT_GUARD_LOG:-/var/log/samurai/boot-guard.log}
boot_device=${SAMURAI_BOOT_GUARD_BOOT_DEVICE:-}
logdump_device=${SAMURAI_BOOT_GUARD_LOGDUMP_DEVICE:-}
reboot_cmd=${SAMURAI_BOOT_GUARD_REBOOT_CMD:-reboot}
default_wait=${SAMURAI_BOOT_GUARD_WAIT_SECONDS:-600}
interval=${SAMURAI_BOOT_GUARD_INTERVAL:-2}

marker=$state_dir/armed
confirm_file=$run_dir/confirmed
boot_image=$state_dir/boot-rollback.img
logdump_image=$state_dir/logdump-rollback.img
lock_dir=$run_dir/lock

log_event()
{
	mkdir -p "${log_file%/*}"
	printf '%s %s\n' "$(date -Is)" "$*" >>"$log_file"
}

monotonic_seconds()
{
	awk '{ print int($1) }' /proc/uptime
}

die()
{
	log_event "ERROR $*"
	printf 'ERROR: %s\n' "$*" >&2
	exit 1
}

partition_by_label()
{
	label=$1
	path=$(readlink -f "/dev/disk/by-partlabel/$label" 2>/dev/null || true)
	[ -n "$path" ] || die "no block device for PARTLABEL=$label"
	[ -e "$path" ] || die "PARTLABEL=$label does not exist: $path"
	printf '%s\n' "$path"
}

resolve_devices()
{
	[ -n "$boot_device" ] || boot_device=$(partition_by_label boot)
	[ -n "$logdump_device" ] || logdump_device=$(partition_by_label logdump)
	[ "$boot_device" != "$logdump_device" ] ||
		die "boot and logdump resolved to the same device"
}

device_size()
{
	if command -v blockdev >/dev/null 2>&1 &&
		blockdev --getsize64 "$1" >/dev/null 2>&1; then
		blockdev --getsize64 "$1"
	else
		stat -c %s "$1"
	fi
}

is_mounted()
{
	if awk -v device="$1" \
		'$1 == device { found = 1 } END { exit(found ? 0 : 1) }' \
		/proc/mounts; then
		return 0
	fi
	return 1
}

is_read_only()
{
	if command -v blockdev >/dev/null 2>&1 &&
		blockdev --getro "$1" >/dev/null 2>&1; then
		if [ "$(blockdev --getro "$1")" -ne 0 ]; then
			return 0
		fi
		return 1
	fi
	if [ -w "$1" ]; then
		return 1
	fi
	return 0
}

sha256_file()
{
	sha256sum "$1" | cut -d ' ' -f 1
}

verify_pair()
{
	expected_boot=$1
	expected_logdump=$2

	resolve_devices
	for item in boot logdump; do
		case $item in
		boot)
			image=$boot_image
			device=$boot_device
			expected=$expected_boot
			;;
		logdump)
			image=$logdump_image
			device=$logdump_device
			expected=$expected_logdump
			;;
		esac

		[ -f "$image" ] || die "$item rollback image is missing: $image"
		[ -e "$device" ] || die "$item target is missing: $device"
		[ "$(device_size "$device")" = "$(stat -c %s "$image")" ] ||
			die "$item image/partition size mismatch"
		[ "$(sha256_file "$image")" = "$expected" ] ||
			die "$item rollback image hash mismatch"
		if is_mounted "$device"; then
			die "$item target is mounted: $device"
		fi
		if is_read_only "$device"; then
			die "$item target is read-only: $device"
		fi
	done
}

read_marker()
{
	[ -f "$marker" ] || return 1
	# The marker is generated by "arm" and contains only fixed key=value lines.
	. "$marker"
	case ${armed_wait_seconds:-} in
	''|*[!0-9]*) die "invalid armed_wait_seconds in $marker" ;;
	esac
	[ "${armed_wait_seconds:-0}" -ge 60 ] &&
		[ "${armed_wait_seconds:-0}" -le 1800 ] ||
		die "armed_wait_seconds is outside 60..1800"
	[ -n "${armed_boot_sha256:-}" ] || die "marker has no boot hash"
	[ -n "${armed_logdump_sha256:-}" ] || die "marker has no logdump hash"
}

acquire_lock()
{
	mkdir -p "$run_dir"
	if ! mkdir "$lock_dir" 2>/dev/null; then
		die "another boot guard instance owns $lock_dir"
	fi
	trap 'rmdir "$lock_dir" 2>/dev/null || true' EXIT HUP INT TERM
}

write_image()
{
	name=$1
	image=$2
	device=$3
	expected=$4

	log_event "ROLLBACK_WRITE_BEGIN name=$name device=$device sha256=$expected"
	dd if="$image" of="$device" bs=4M conv=fsync
	sync
	if command -v blockdev >/dev/null 2>&1; then
		blockdev --flushbufs "$device" || true
	fi
	actual=$(sha256sum "$device" | cut -d ' ' -f 1)
	[ "$actual" = "$expected" ] ||
		die "$name readback mismatch: expected=$expected actual=$actual"
	log_event "ROLLBACK_WRITE_OK name=$name device=$device sha256=$actual"
}

disarm()
{
	rm -f "$marker"
	rm -f "$confirm_file"
	log_event "DISARMED"
}

arm()
{
	mkdir -p "$state_dir" "$run_dir" "${log_file%/*}"
	[ ! -e "$marker" ] || die "boot guard is already armed"
	[ -f "$boot_image" ] || die "missing $boot_image"
	[ -f "$logdump_image" ] || die "missing $logdump_image"
	wait=${SAMURAI_BOOT_GUARD_ARM_WAIT_SECONDS:-$default_wait}
	case $wait in
	''|*[!0-9]*) die "wait seconds is not numeric: $wait" ;;
	esac
	[ "$wait" -ge 60 ] && [ "$wait" -le 1800 ] ||
		die "wait seconds is outside 60..1800"

	boot_sha=$(sha256_file "$boot_image")
	logdump_sha=$(sha256_file "$logdump_image")
	verify_pair "$boot_sha" "$logdump_sha"
	rm -f "$confirm_file"
	cat >"$marker" <<EOF
armed_at="$(date -Is)"
armed_wait_seconds=$wait
armed_boot_sha256=$boot_sha
armed_logdump_sha256=$logdump_sha
EOF
	sync
	log_event "ARMED wait=${wait}s boot_sha256=$boot_sha logdump_sha256=$logdump_sha"
	printf 'ARMED wait=%ss boot_sha256=%s logdump_sha256=%s\n' \
		"$wait" "$boot_sha" "$logdump_sha"
}

confirm()
{
	mkdir -p "$run_dir"
	: >"$confirm_file"
	log_event "CONFIRM_REQUESTED"
	printf 'CONFIRM_REQUESTED\n'
}

monitor()
{
	mkdir -p "$run_dir" "${log_file%/*}"
	if ! read_marker; then
		log_event "MONITOR no marker; nothing armed"
		while [ ! -e "$marker" ]; do
			sleep 300
		done
		log_event "MONITOR marker appeared"
		read_marker
	fi
	acquire_lock
	verify_pair "$armed_boot_sha256" "$armed_logdump_sha256"
	log_event "MONITOR start wait=${armed_wait_seconds}s"

	start=$(monotonic_seconds)
	while :; do
		if [ -e "$confirm_file" ]; then
			disarm
			log_event "MONITOR confirmed; rollback disarmed"
			return 0
		fi
		now=$(monotonic_seconds)
		[ $((now - start)) -lt "$armed_wait_seconds" ] || break
		sleep "$interval"
	done

	log_event "MONITOR timeout; restoring rollback pair"
	# Write logdump first and boot last.  A successful boot write then leaves
	# a consistent pair even if writing the secondary FAT image failed.
	log_event "ROLLBACK_WRITE_ORDER logdump,boot"
	write_image logdump "$logdump_image" "$logdump_device" "$armed_logdump_sha256"
	write_image boot "$boot_image" "$boot_device" "$armed_boot_sha256"
	disarm
	sync
	log_event "ROLLBACK_COMPLETE; rebooting"
	# shellcheck disable=SC2086
	$reboot_cmd
}

status()
{
	printf 'marker=%s\n' "$([ -e "$marker" ] && echo armed || echo absent)"
	printf 'confirmed=%s\n' "$([ -e "$confirm_file" ] && echo yes || echo no)"
	printf 'state_dir=%s\n' "$state_dir"
	printf 'boot_image=%s\n' "$boot_image"
	printf 'logdump_image=%s\n' "$logdump_image"
	[ ! -f "$marker" ] || cat "$marker"
}

case ${1:-status} in
arm) arm ;;
confirm) confirm ;;
disarm) disarm ;;
monitor) monitor ;;
status) status ;;
*)
	echo 'Usage: samurai-boot-guard arm|confirm|disarm|monitor|status' >&2
	exit 2
	;;
esac
